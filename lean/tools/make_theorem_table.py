"""Write the table of top-level theorems against the items of Section 9.5.

Usage: python make_theorem_table.py <scope.json> <Lake package dir> <theorems.json> <audit log> <out md> <out json>

Module and line of each theorem are found in the sources; the axioms are read
from the `#print axioms` lines of the audit log (output of ScopeAxioms.lean).
Fails if a theorem of the table has no `#print axioms` result.
"""
import json
import os
import re
import sys

scope = json.load(open(sys.argv[1], encoding="utf-8"))
formal = sys.argv[2]
table = json.load(open(sys.argv[3], encoding="utf-8"))
log = open(sys.argv[4], encoding="utf-8-sig", errors="replace").read()
out_md, out_json = sys.argv[5], sys.argv[6]

ITEMS = {
    "A": "Definitions and invariances",
    "B": "Constants",
    "C": "The lattice case",
    "D": "Analytic part of the two-site theorem",
    "E": "Checking functions (soundness)",
    "F": "Reduction of the theorem",
}

decl = re.compile(r"^\s*(?:@\[[^\]]*\]\s*)*(?:private\s+|protected\s+|noncomputable\s+)*"
                  r"(?:theorem|lemma)\s+([^\s:({\[]+)")
where = {}
for m in scope["order"]:
    stack = []
    path = os.path.join(formal, scope["modules"][m]["path"])
    for ln, line in enumerate(open(path, encoding="utf-8"), 1):
        mm = re.match(r"^namespace\s+(\S+)", line)
        if mm:
            stack.append(mm.group(1))
            continue
        mm = re.match(r"^end\s+(\S+)", line)
        if mm and stack and stack[-1] == mm.group(1):
            stack.pop()
            continue
        mm = decl.match(line)
        if mm:
            where.setdefault(".".join(stack + [mm.group(1)]), (m, ln))

flat = re.sub(r"\s+", " ", log)
axioms = {}
for mm in re.finditer(r"'([^']+)' depends on axioms: \[([^\]]*)\]", flat):
    axioms[mm.group(1)] = [a.strip() for a in mm.group(2).split(",") if a.strip()]
for mm in re.finditer(r"'([^']+)' does not depend on any axioms", flat):
    axioms[mm.group(1)] = []

rows = []
missing = []
for t in table:
    n = t["name"]
    if n not in axioms:
        missing.append(n)
        continue
    mod, ln = where.get(n, ("?", 0))
    rows.append(dict(item=t["item"], supports=t["supports"], name=n, module=mod, line=ln, axioms=axioms[n]))
if missing:
    sys.exit(f"no #print axioms result for: {missing}")

STD = ["propext", "Classical.choice", "Quot.sound"]
SHORT = {"propext": "P", "Classical.choice": "C", "Quot.sound": "Q"}
L = ["# Theorems of the formal development", "",
     "The 130 theorems that represent the items of Section 9.5 of the paper, by name relative to the namespace "
     "`BccSharp.Coulomb`, with module and line and their axioms (P = `propext`, C = `Classical.choice`, "
     "Q = `Quot.sound`), as reported by `#print axioms` in the axiom audit. Generated by `tools/make_theorem_table.py`.", ""]
L.append("| Item | Supports | Lean theorem | Module | Axioms |")
L.append("|---|---|---|---|---|")
P = "BccSharp.Coulomb."
for r in rows:
    ax = "".join(SHORT.get(a, "[" + a + "]") for a in STD if a in r["axioms"])
    ax += "".join("[" + a + "]" for a in r["axioms"] if a not in STD)
    name = r["name"][len(P):] if r["name"].startswith(P) else r["name"]
    L.append(f"| {r['item']} | {r['supports']} | `{name}` | `{r['module']}`:{r['line']} | {ax or 'none'} |")
with open(out_md, "w", encoding="utf-8", newline="\n") as fh:
    fh.write("\n".join(L) + "\n")
with open(out_json, "w", encoding="utf-8", newline="\n") as fh:
    json.dump(rows, fh, indent=1, ensure_ascii=False)
    fh.write("\n")
sets = {}
for r in rows:
    sets.setdefault(tuple(r["axioms"]), 0)
    sets[tuple(r["axioms"])] += 1
other = [r["name"] for r in rows if any(a not in STD for a in r["axioms"])]
print(f"{len(rows)} theorems; axiom sets: {sets}; outside the three: {other}")
for k in ITEMS:
    print(f"  {k} {ITEMS[k]}: {sum(1 for r in rows if r['item'] == k)}")
